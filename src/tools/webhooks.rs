//! Webhook tools. Henrri pushes events; it has no route to list or manage
//! subscriptions, which live in its interface. These tools cover the rest of
//! the specification's webhook section: what can be sent, how to verify it,
//! and what this server received.

use std::time::{Duration, SystemTime};

use rmcp::{Json, handler::server::wrapper::Parameters};
use serde::{Deserialize, Serialize};

use crate::{
    error::{Error, ToolError},
    server::HenrriServer,
    webhooks::{self, Envelope, EventType, ReceivedEvent, Verdict},
};

/// What `list_webhook_event_types` answers.
#[derive(Debug, Clone, Serialize, schemars::JsonSchema)]
pub struct EventCatalogue {
    /// Every event Henrri can send.
    pub events: Vec<EventType>,
    /// How deliveries are signed and sent.
    pub delivery: String,
}

/// Arguments of `verify_webhook_signature`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct VerifyArgs {
    /// The raw request body, exactly as received.
    pub body: String,
    /// The `X-Henrri-Webhook-Signature` header: `sha256=<hex>`.
    pub signature: String,
    /// The `X-Henrri-Webhook-Timestamp` header: unix seconds.
    pub timestamp: String,
    /// How old a delivery may be, in seconds. Default 300; 0 skips the check,
    /// to verify an old delivery from Henrri's history.
    pub tolerance_secs: Option<u64>,
}

/// What `verify_webhook_signature` answers.
#[derive(Debug, Clone, Serialize, schemars::JsonSchema)]
pub struct Verification {
    /// True when the delivery comes from Henrri, unmodified.
    pub valid: bool,
    /// The verdict, machine-readable.
    pub verdict: Verdict,
    /// The verdict, in a sentence.
    pub reason: String,
    /// The envelope, when the signature is valid.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub envelope: Option<Envelope>,
}

/// Arguments of `list_received_webhook_events`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct ReceivedArgs {
    /// Only this event, e.g. `document.finalized`.
    pub event: Option<String>,
    /// How many, newest first. Default 50.
    pub limit: Option<usize>,
}

/// What `list_received_webhook_events` answers.
#[derive(Debug, Clone, Serialize, schemars::JsonSchema)]
pub struct ReceivedEvents {
    /// How many deliveries are returned.
    pub returned: usize,
    /// The deliveries, newest first. Read the resource with the tool the
    /// event catalogue names.
    pub events: Vec<ReceivedEvent>,
    /// Where the deliveries come from, and why there may be none.
    pub note: String,
}

#[allow(missing_docs, reason = "the router function is generated by the macro")]
#[rmcp::tool_router(router = webhooks_router, vis = "pub")]
impl HenrriServer {
    /// Every webhook event Henrri can send (customer, document, item and
    /// payment events, plus the test ping), what each means, and the tool that
    /// reads the resource it names.
    #[rmcp::tool(annotations(
        title = "List webhook event types",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = false
    ))]
    pub async fn list_webhook_event_types(&self) -> Result<Json<EventCatalogue>, ToolError> {
        Ok(Json(EventCatalogue {
            events: webhooks::EVENTS.to_vec(),
            delivery: "Subscriptions are set in Henrri (settings, webhooks): a callback URL and the events. Each delivery is a POST of {event, date, id, companyId, delivery}, signed with HMAC-SHA256(secret, \"{timestamp}.{rawBody}\") in X-Henrri-Webhook-Signature: sha256=<hex>, with X-Henrri-Webhook-Timestamp and X-Henrri-Webhook-Delivery. It is sent once, with no retry: answer 2xx. Run this server over HTTP with HENRRI_WEBHOOK_SECRET and point the callback at /webhooks to receive them.".to_owned(),
        }))
    }

    /// Check that a webhook delivery really comes from Henrri and was not
    /// modified, with the secret in HENRRI_WEBHOOK_SECRET. Pass the raw body
    /// and the two headers. Nothing is sent anywhere.
    #[rmcp::tool(annotations(
        title = "Verify a webhook signature",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = false
    ))]
    pub async fn verify_webhook_signature(
        &self,
        Parameters(args): Parameters<VerifyArgs>,
    ) -> Result<Json<Verification>, ToolError> {
        let Some(secret) = self.config().webhook_secret.as_ref() else {
            return Err(Error::invalid(
                "HENRRI_WEBHOOK_SECRET is not set: copy the signing secret from Henrri's webhook settings into it",
            )
            .into());
        };
        let tolerance = match args.tolerance_secs {
            Some(0) => Duration::MAX,
            Some(secs) => Duration::from_secs(secs),
            None => webhooks::DEFAULT_TOLERANCE,
        };
        let verdict = webhooks::verify(
            secret.expose(),
            &args.timestamp,
            args.body.as_bytes(),
            &args.signature,
            tolerance,
            SystemTime::now(),
        );
        let envelope = (verdict == Verdict::Valid)
            .then(|| webhooks::parse_envelope(args.body.as_bytes()))
            .flatten();
        Ok(Json(Verification {
            valid: verdict == Verdict::Valid,
            verdict,
            reason: verdict.explain().to_owned(),
            envelope,
        }))
    }

    /// The webhook deliveries this server received and verified, newest
    /// first: event, resource id, date. Deliveries arrive only while the
    /// server runs over HTTP with HENRRI_WEBHOOK_SECRET, at `/webhooks`.
    #[rmcp::tool(annotations(
        title = "List received webhook events",
        read_only_hint = true,
        idempotent_hint = false,
        open_world_hint = false
    ))]
    pub async fn list_received_webhook_events(
        &self,
        Parameters(args): Parameters<ReceivedArgs>,
    ) -> Result<Json<ReceivedEvents>, ToolError> {
        let events = self.inbox().recent(
            args.event
                .as_deref()
                .map(str::trim)
                .filter(|e| !e.is_empty()),
            args.limit.unwrap_or(50).clamp(1, webhooks::INBOX_CAPACITY),
        );
        let note = if self.config().http_bind.is_none() {
            "this server runs over stdio, so it cannot receive webhooks: run it with --http and HENRRI_WEBHOOK_SECRET, and set the callback to https://<host>/webhooks in Henrri"
        } else if self.config().webhook_secret.is_none() {
            "HENRRI_WEBHOOK_SECRET is not set: deliveries to /webhooks are refused until it is"
        } else {
            "verified deliveries received at /webhooks since this process started, kept in memory (the last 200)"
        };
        Ok(Json(ReceivedEvents {
            returned: events.len(),
            events,
            note: note.to_owned(),
        }))
    }
}
