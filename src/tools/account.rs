//! Who this server acts as: the user, the company, connectivity, credits.

use rmcp::{Json, handler::server::wrapper::Parameters};
use serde::{Deserialize, Serialize};
use serde_json::Value;

use crate::{
    client::{Request, Usage},
    error::ToolError,
    server::HenrriServer,
    tools::{ApiObject, Id},
};

/// Arguments of the tools that read one user.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct UserArgs {
    /// The user id, as `whoami` shows it under `user.id`. Reading another user
    /// than yourself requires being an administrator of the same company.
    pub user_id: Id,
}

/// Arguments of the tools that read one company.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct CompanyArgs {
    /// The company id, as `whoami` shows it under `company.id`.
    pub company_id: Id,
}

/// What `ping` answers.
#[derive(Debug, Clone, Serialize, schemars::JsonSchema)]
pub struct Pong {
    /// True when Henrri accepted the token.
    pub ok: bool,
    /// The environment this server talks to: production or sandbox.
    pub environment: String,
    /// The API root.
    pub base_url: String,
    /// What Henrri answered.
    pub response: Value,
}

/// What `get_api_usage` answers.
#[derive(Debug, Clone, Serialize, schemars::JsonSchema)]
pub struct ApiUsage {
    /// The environment the counters belong to.
    pub environment: String,
    /// The counters Henrri sent with its last answer.
    pub usage: Usage,
    /// How credits work, so the numbers mean something.
    pub pricing: String,
}

#[allow(missing_docs, reason = "the router function is generated by the macro")]
#[rmcp::tool_router(router = account_router, vis = "pub")]
impl HenrriServer {
    /// Check that the credentials work: an authenticated hello world. Use it
    /// first when something fails, to tell a credential problem from a request
    /// problem.
    #[rmcp::tool(annotations(
        title = "Check the connection",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn ping(&self) -> Result<Json<Pong>, ToolError> {
        let response: Value = self
            .client()
            .call(Request::get("/v1/secures/hello-world"))
            .await?;
        let config = self.config();
        Ok(Json(Pong {
            ok: true,
            environment: config.environment.as_str().to_owned(),
            base_url: config.base_url.clone(),
            response,
        }))
    }

    /// Who this server acts as: the authenticated user (id, email, role) and
    /// their company (id, name, SIRET, subscription plan, address). Call it
    /// first: most other ids start from here.
    #[rmcp::tool(annotations(
        title = "Who am I",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn whoami(&self) -> Result<Json<ApiObject>, ToolError> {
        let me: Value = self.client().call(Request::get("/v1/users/me")).await?;
        Ok(Json(ApiObject::from_value(me)))
    }

    /// Read one user of the company: name, email, role, enabled, two-factor.
    #[rmcp::tool(annotations(
        title = "Get a user",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_user(
        &self,
        Parameters(args): Parameters<UserArgs>,
    ) -> Result<Json<ApiObject>, ToolError> {
        let user: Value = self
            .client()
            .call(Request::get(format!("/v1/users/{}", args.user_id)))
            .await?;
        Ok(Json(ApiObject::from_value(user)))
    }

    /// Read the postal address of one user of the company.
    #[rmcp::tool(annotations(
        title = "Get a user's address",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_user_address(
        &self,
        Parameters(args): Parameters<UserArgs>,
    ) -> Result<Json<ApiObject>, ToolError> {
        let address: Value = self
            .client()
            .call(Request::get(format!("/v1/users/{}/address", args.user_id)))
            .await?;
        Ok(Json(ApiObject::from_value(address)))
    }

    /// Read the company of the authenticated user: name, SIRET, APE code,
    /// email, website, subscription plan, address.
    #[rmcp::tool(annotations(
        title = "Get my company",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_my_company(&self) -> Result<Json<ApiObject>, ToolError> {
        let company: Value = self
            .client()
            .call(Request::get("/v1/users/companies"))
            .await?;
        Ok(Json(ApiObject::from_value(company)))
    }

    /// Read a company by id: name, SIRET, APE code, subscription plan,
    /// address. Only your own company is in scope; any other id answers 404.
    #[rmcp::tool(annotations(
        title = "Get a company",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_company(
        &self,
        Parameters(args): Parameters<CompanyArgs>,
    ) -> Result<Json<ApiObject>, ToolError> {
        let company: Value = self
            .client()
            .call(Request::get(format!("/v1/companies/{}", args.company_id)))
            .await?;
        Ok(Json(ApiObject::from_value(company)))
    }

    /// Read the postal address of a company by id: street, city, postal code,
    /// country.
    #[rmcp::tool(annotations(
        title = "Get a company's address",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_company_address(
        &self,
        Parameters(args): Parameters<CompanyArgs>,
    ) -> Result<Json<ApiObject>, ToolError> {
        let address: Value = self
            .client()
            .call(Request::get(format!(
                "/v1/companies/{}/address",
                args.company_id
            )))
            .await?;
        Ok(Json(ApiObject::from_value(address)))
    }

    /// The API credits used and left this month, and the rate limit, as Henrri
    /// reported them on its last answer. Finalizing an invoice or credit note
    /// costs 8 credits, finalizing another document 2, validating a quote 2;
    /// everything else is free. Check before a batch of finalizations.
    #[rmcp::tool(annotations(
        title = "Get API credit usage",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_api_usage(&self) -> Result<Json<ApiUsage>, ToolError> {
        // The counters only travel in headers: make one free call if none came yet.
        if self.client().usage().credits_used.is_none() {
            let _: Value = self
                .client()
                .call(Request::get("/v1/secures/hello-world"))
                .await?;
        }
        Ok(Json(ApiUsage {
            environment: self.config().environment.as_str().to_owned(),
            usage: self.client().usage(),
            pricing: "Credits are charged only when a document is issued: finalizing an accounting document (invoice, credit note) costs 8, finalizing any other document (quote, delivery note…) 2, validating a quote 2. Reads, drafts, lines, customers and failed calls are free. The quota resets on the 1st of each month (UTC); the sandbox is unlimited.".to_owned(),
        }))
    }
}
