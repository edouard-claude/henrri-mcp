//! Revenue statistics: 2 routes.

use rmcp::{Json, handler::server::wrapper::Parameters};
use serde::Deserialize;
use serde_json::Value;

use crate::{
    client::Request,
    error::{Error, ToolError},
    server::HenrriServer,
    tools::{ApiObject, Listing},
};

/// Arguments of the revenue tools.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct RevenueArgs {
    /// The year, four digits: 2026.
    pub year: i32,
}

fn check_year(year: i32) -> Result<i32, Error> {
    if (1000..=9999).contains(&year) {
        Ok(year)
    } else {
        Err(Error::invalid(format!(
            "year is a four-digit year such as 2026, got {year}"
        )))
    }
}

#[allow(missing_docs, reason = "the router function is generated by the macro")]
#[rmcp::tool_router(router = revenues_router, vis = "pub")]
impl HenrriServer {
    /// A year's revenue, 1 January to 31 December, in euros: services
    /// (labour), products (goods), the margin on products, and the service
    /// hours billed.
    #[rmcp::tool(annotations(
        title = "Get yearly revenue",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_yearly_revenue(
        &self,
        Parameters(args): Parameters<RevenueArgs>,
    ) -> Result<Json<ApiObject>, ToolError> {
        let year = check_year(args.year)?;
        let revenue: Value = self
            .client()
            .call(Request::get(format!("/v1/revenues/{year}")))
            .await?;
        Ok(Json(ApiObject::from_value(revenue)))
    }

    /// A year's revenue month by month (1 = January), in euros: services,
    /// products, margin on products, service hours.
    #[rmcp::tool(annotations(
        title = "Get monthly revenue",
        read_only_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_monthly_revenue(
        &self,
        Parameters(args): Parameters<RevenueArgs>,
    ) -> Result<Json<Listing>, ToolError> {
        let year = check_year(args.year)?;
        let months: Value = self
            .client()
            .call(Request::get(format!("/v1/revenues/{year}/months")))
            .await?;
        Ok(Json(Listing::from_value(months)))
    }
}
