//! MCP prompts: the four workflows a small business actually runs in Henrri.
//!
//! A prompt here is a script, not a personality. Each one names the tools to
//! call, in order, and where to stop and ask. The rule they share: read before
//! writing, show the total before finalizing, and never finalize, validate or
//! record a payment without an explicit yes.

use rmcp::{
    ErrorData as McpError,
    handler::server::{router::prompt::PromptRouter, wrapper::Parameters},
    model::{PromptMessage, Role},
};
use serde::Deserialize;

use crate::server::HenrriServer;

/// Arguments of `draft_invoice`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct DraftInvoiceArgs {
    /// Who is invoiced: a customer name, as Henrri knows it or not yet.
    pub customer: String,
    /// What is invoiced, in plain words: "3 jours de développement à 600 € HT".
    pub what: String,
    /// The kind of document: invoice (default), quotation, creditNote…
    pub kind: Option<String>,
}

/// Arguments of `chase_unpaid`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct ChaseArgs {
    /// One customer to focus on; every customer when absent.
    pub customer: Option<String>,
}

/// Arguments of `revenue_report`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct ReportArgs {
    /// The year, e.g. 2026. Default: the current year.
    pub year: Option<i32>,
}

/// Arguments of `quote_to_invoice`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct QuoteArgs {
    /// The quote: its number (D-2026-…), its id, or the customer's name.
    pub quote: String,
}

/// The prompt router this server exposes.
pub fn router() -> PromptRouter<HenrriServer> {
    HenrriServer::prompt_router()
}

#[allow(missing_docs, reason = "the router function is generated by the macro")]
#[rmcp::prompt_router]
impl HenrriServer {
    /// Draft an invoice (or a quote) for a customer from a plain description,
    /// review it with the person, and finalize it only on their yes.
    #[rmcp::prompt(name = "draft_invoice")]
    pub async fn draft_invoice_prompt(
        &self,
        Parameters(args): Parameters<DraftInvoiceArgs>,
    ) -> std::result::Result<Vec<PromptMessage>, McpError> {
        let kind = args.kind.unwrap_or_else(|| "invoice".to_owned());
        let text = format!(
            "Prepare a Henrri {kind} for \"{customer}\": {what}.\n\
             \n\
             1. `list_customers` with search = the customer's name. If several match, ask which. \
                If none, ask for what `create_customer` needs (professional or individual, a contact's \
                last name, the address) and create it.\n\
             2. `list_document_types`: take the id whose documentKind is {kind}.\n\
             3. `create_document` with that type and the customer: it is an empty draft.\n\
             4. For each thing invoiced, `list_items` with search to reuse a catalogue item; \
                otherwise `add_document_line` with kind = item and an inline `item` (description, \
                vat_percent, selling_price_without_tax, item_category_id from `list_item_categories`). \
                Quantities and unit prices excluding tax; VAT in percent (20 for 20 %).\n\
             5. `get_document_with_all`: show the person the lines, the total excluding tax, the VAT \
                per rate and the total including tax, in euros (1 234,50 €).\n\
             6. Stop and ask. Only on an explicit yes, `finalize_document` with confirm: true. Say \
                first that it locks the document for good and costs credits (8 for an invoice or credit \
                note, 2 otherwise). If Henrri answers FIRST_ACCOUNTING_DOCUMENT_MONTH, say so and retry \
                with confirm_first_of_month: true after a second yes.\n\
             7. `get_document_pdf` and give the path of the file.\n\
             \n\
             Without a yes, leave the draft as it is and give its id.",
            customer = args.customer,
            what = args.what,
        );
        Ok(vec![PromptMessage::new_text(Role::User, text)])
    }

    /// List what is overdue, per customer, and draft reminder messages. Reads
    /// and drafts only: nothing is sent or recorded.
    #[rmcp::prompt(name = "chase_unpaid")]
    pub async fn chase_unpaid_prompt(
        &self,
        Parameters(args): Parameters<ChaseArgs>,
    ) -> std::result::Result<Vec<PromptMessage>, McpError> {
        let scope = args.customer.map_or_else(
            || "every customer".to_owned(),
            |c| format!("the customer \"{c}\" (find its id with `list_customers`, then use `list_customer_payment_milestones`)"),
        );
        let text = format!(
            "Find what my customers owe me in Henrri, for {scope}. This is read-only: do not pay, \
             change or delete anything.\n\
             \n\
             1. `list_payment_milestones` with is_overdue = true (page through with `page` while \
                has_next is true): every unpaid milestone past its due date.\n\
             2. For each document concerned, `get_document` for its number, customer and total.\n\
             3. Group per customer: documents, amounts due, how many days late.\n\
             4. Also `list_payment_milestones` with is_paid = false and a due date in the next 15 \
                days (`from_date` today, `to_date` \"in 15 days\") for what is about to fall due.\n\
             \n\
             Present a table per customer, the total overdue in euros, and for each customer a short, \
             courteous reminder message in French quoting the document numbers and amounts. Do not send \
             anything: the person sends the reminders themselves."
        );
        Ok(vec![PromptMessage::new_text(Role::User, text)])
    }

    /// A revenue report for a year: totals, month by month, best customers
    /// and items. Reads only.
    #[rmcp::prompt(name = "revenue_report")]
    pub async fn revenue_report_prompt(
        &self,
        Parameters(args): Parameters<ReportArgs>,
    ) -> std::result::Result<Vec<PromptMessage>, McpError> {
        let year = args
            .year
            .map_or_else(|| "the current year".to_owned(), |y| y.to_string());
        let text = format!(
            "Write my revenue report in Henrri for {year}. Read-only: change nothing.\n\
             \n\
             1. `get_yearly_revenue` for the totals: services, products, margin on products, hours.\n\
             2. `get_monthly_revenue` for the month-by-month split.\n\
             3. `list_best_customers` and `list_best_selling_items` for the same year.\n\
             4. `list_payment_milestones` with is_paid = false for what is still to collect.\n\
             \n\
             Present the total, a month table with the best and the worst month, the five best \
             customers and items, what remains to collect, and three lines on what stands out. Euros, \
             French formatting (1 234,50 €)."
        );
        Ok(vec![PromptMessage::new_text(Role::User, text)])
    }

    /// Turn an accepted quote into an invoice: check it, record the
    /// acceptance if needed, transform, review, finalize on a yes.
    #[rmcp::prompt(name = "quote_to_invoice")]
    pub async fn quote_to_invoice_prompt(
        &self,
        Parameters(args): Parameters<QuoteArgs>,
    ) -> std::result::Result<Vec<PromptMessage>, McpError> {
        let text = format!(
            "Invoice the quote \"{quote}\" in Henrri.\n\
             \n\
             1. Find it: `list_documents` with document_types = [\"quotation\"] and search = \"{quote}\" \
                (or `get_document` if it is an id). If several match, ask which.\n\
             2. It must be finalized. If it is a draft, show it and ask before `finalize_document` \
                (confirm: true; 2 credits).\n\
             3. If the person says the customer signed it and it is not `validated`, ask for the \
                signer's name, email and IP, then `validate_quotation` with confirm: true (2 credits).\n\
             4. `transform_quote_to_invoice`: it answers the new draft invoice, with its own id.\n\
             5. `get_document_with_all` on the invoice: show lines and totals, and \
                `list_document_payment_milestones` for its schedule.\n\
             6. Stop and ask. Only on an explicit yes, `finalize_document` on the invoice with \
                confirm: true: it locks it for good and costs 8 credits.\n\
             7. `get_document_pdf` and give the path.",
            quote = args.quote,
        );
        Ok(vec![PromptMessage::new_text(Role::User, text)])
    }
}
